"""Render the strategy report from computed artefacts (no hard-coded numbers)."""
from __future__ import annotations

import json

from .config import Settings, load_settings
from .errors import NotBuiltError
from .logging_conf import get_logger
from .warehouse import query_df

log = get_logger(__name__)


def _load(s: Settings, name: str) -> dict:
    p = s.processed_dir / name
    if not p.exists():
        raise NotBuiltError(f"{name} not found. Run 'ingomob run-all' first.")
    return json.loads(p.read_text())


def _table(headers, rows) -> str:
    h = "| " + " | ".join(str(x) for x in headers) + " |"
    sep = "| " + " | ".join("---" for _ in headers) + " |"
    body = "\n".join("| " + " | ".join(str(c) for c in r) + " |" for r in rows)
    return "\n".join([h, sep, body])


def build_report(settings: Settings | None = None) -> str:
    s = settings or load_settings()
    fc = _load(s, "forecast_metrics.json")
    tq = _load(s, "transit_quality.json")
    st = _load(s, "siting_summary.json")
    dq = _load(s, "data_quality_report.json")

    routes = query_df("SELECT * FROM mart_route_service ORDER BY avg_peak_headway_min")
    routes["route_short_name"] = routes["route_short_name"].astype(str)
    districts = query_df("SELECT * FROM mart_district_scorecard ORDER BY avg_daily_traffic DESC")
    window = query_df("SELECT CAST(MIN(date) AS VARCHAR) AS a, CAST(MAX(date) AS VARCHAR) AS b FROM fact_traffic")
    cv, summ = fc["cv"], fc["cv"]["summary"]

    ladder = _table(
        ["Predictor", "MAE (mean ± std)", "RMSE", "R²"],
        [[label,
          f'{summ[k]["mae"]["mean"]} ± {summ[k]["mae"]["std"]}',
          summ[k]["rmse"]["mean"], summ[k]["r2"]["mean"]]
         for k, label in [("last_value", "Last value (t−24h)"),
                          ("seasonal_naive", "Seasonal-naive (t−168h)"),
                          ("calendar_only", "Calendar + weather model"),
                          ("model", "**Full model (lags + calendar)**")]])

    route_rows = [[f"L{r.route_short_name}", r.route_long_name, int(r.trips_weekday),
                   f"{r.avg_peak_headway_min} min", f"{r.span_hours} h", int(r.n_stops)]
                  for r in routes.itertuples()]
    district_rows = [[r.district, f"{int(r.avg_daily_traffic):,}", int(r.n_detectors),
                      int(r.n_stops), int(r.weekday_departures), int(r.n_charging_points),
                      f"{int(r.total_charging_kw):,}"] for r in districts.itertuples()]
    siting_rows = [[r["rank"], r["nearest_district"], r["gap_score"], r["demand"], r["supply"],
                    f"{r['lat']:.5f}, {r['lon']:.5f}"] for r in st["recommendations"]]

    mode_banner = (
        "> **Source mode: `demo`.** Figures below come from a seeded synthetic dataset built to "
        "the real Ingolstadt/VGI schemas. They demonstrate the method, **not** the state of the "
        "city. Run `ingomob run-all --source live` to execute the same pipeline on official "
        "open data."
        if fc.get("source", s.source) == "demo" else
        "> **Source mode: `live`.** Built from official open-data downloads (DWD, VGI GTFS, "
        "OpenStreetMap/Overpass)."
    )

    md = f"""# Ingolstadt Mobility Intelligence — Analysis Report

Analysis window: **{window.a[0]} → {window.b[0]}** · generated by the IngoMobility pipeline.

{mode_banner}

---

## Executive summary

- **The demand model beats every baseline, but modestly.** Across
  {cv['n_folds']} rolling-origin folds ({cv['horizon_days']}-day horizons) it achieves
  **MAE {summ['model']['mae']['mean']} ± {summ['model']['mae']['std']}**
  (R² {summ['model']['r2']['mean']}), versus
  {summ['seasonal_naive']['mae']['mean']} for a seasonal-naive baseline and
  {summ['calendar_only']['mae']['mean']} for a calendar-only model. The honest headline is the
  **{fc['lift_over_calendar_only_pct']} % improvement over calendar-only** — the seasonal-naive
  comparison flatters the model and should not be quoted alone.
- **Public-transport supply is uneven.** Mean weekday peak headway is
  {tq['avg_peak_headway_min']} min, ranging from L{tq['best_route']['line']}
  ({tq['best_route']['headway_min']} min) to L{tq['worst_route']['line']}
  ({tq['worst_route']['headway_min']} min). {tq['n_underserved_stops']} stops fall in the bottom
  service quintile; {tq['n_stops_without_sunday_service']} have no Sunday service at all.
- **Charging shows spatial gaps.** The siting heuristic ranks
  {st['n_recommendations']} candidate locations by unmet demand.
- **Nothing was analysed before it was validated.** The {dq['engine']} data-quality gate checked
  **{dq['total_rows_checked']:,} rows** against {len(dq['checks'])} rules and the pipeline aborts
  if any rule fails.

---

## 1. Method

Raw sources → data-quality gate → DuckDB star schema (dimensions → facts → marts) → analytics,
ML and BI. Every stage is deterministic and re-runnable via `ingomob run-all`.

| Domain | Grain | Rows |
|---|---|---|
| Traffic loop-detector counts | detector × day × hour | {query_df("SELECT COUNT(*) c FROM fact_traffic").c[0]:,} |
| GTFS stop departures | trip × stop | {query_df("SELECT COUNT(*) c FROM fact_stop_departures").c[0]:,} |
| Charging stations | station | {query_df("SELECT COUNT(*) c FROM fact_charging").c[0]:,} |

## 2. Traffic demand patterns

![Hourly profile](figures/hourly_profile.png)

## 3. Demand forecast — evaluated against a ladder of baselines

Rolling-origin cross-validation, expanding window, {cv['n_folds']} folds of
{cv['horizon_days']} days. Reporting a single hold-out against a single weak baseline is the most
common way portfolio projects overstate model quality; this table exists to prevent that.

{ladder}

![Baseline ladder](figures/cv_comparison.png)

Most recent fold ({fc['holdout']['test_start']} → {fc['holdout']['test_end']},
{fc['holdout']['n_train']:,} train / {fc['holdout']['n_test']:,} test rows):

![Forecast](figures/forecast.png)

![Feature importance](figures/feature_importance.png)

**Excluded by design:** `{fc['features_excluded'][0]}`.
See [`docs/model_card.md`](../docs/model_card.md) for assumptions, biases and limits.

## 4. Public-transport service quality

{_table(["Line", "Route", "Weekday trips", "Peak headway", "Span", "Stops"], route_rows)}

![Headway by line](figures/headway.png)

Weekend service runs at **{tq['weekend_service_ratio_pct']} %** of weekday level.
*{tq['method_note']}*

## 5. Charging infrastructure — siting candidates

*Method: {st['method']}.* Caveats: {"; ".join(st['caveats'])}.

{_table(["Rank", "Nearest district", "Gap", "Demand", "Supply", "Lat, Lon"], siting_rows)}

![Siting map](figures/siting_map.png)

## 6. District scorecard

{_table(["District", "Ø traffic/day", "Detectors", "Stops", "Weekday dep.", "Charge pts", "kW"],
        district_rows)}

## 7. Recommendations

1. Use the demand model for day-ahead operational planning, where an
   {fc['lift_over_calendar_only_pct']} % error reduction over a calendar heuristic is
   material — not for long-horizon strategic forecasts, which it was not validated for.
2. Rebalance bus frequency toward the weakest lines; the gap between best and worst peak
   headway is {round(tq['worst_route']['headway_min'] - tq['best_route']['headway_min'], 1)} min.
3. Close the {tq['n_stops_without_sunday_service']} Sunday-service gaps before adding new routes.
4. Treat the charging shortlist as a screening step for a proper siting study, not as a decision.

## 8. Limitations

- On the `demo` source the target is synthetic: metrics show how well the model recovers a known
  stochastic process, not real-world forecast skill.
- The City of Ingolstadt does not publish an open hourly loop-detector feed, so `live` mode covers
  weather, GTFS and charging only (see `DATA_SOURCES.md`).
- The siting score is ordinal and ignores grid capacity, land and cost.
- No GTFS-Realtime, so scheduled service is analysed, not actual punctuality.
"""
    s.reports_dir.mkdir(parents=True, exist_ok=True)
    out = s.reports_dir / "strategy_report.md"
    out.write_text(md, encoding="utf-8")
    log.info("report written: %s", out)
    return str(out)
